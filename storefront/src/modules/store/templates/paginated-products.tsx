import { getProductsListWithSort } from "@lib/data/products"
import { getRegion } from "@lib/data/regions"
import ProductPreview from "@modules/products/components/product-preview"
import { Pagination } from "@modules/store/components/pagination"
import { SortOptions } from "@modules/store/components/refinement-list/sort-products"

const PRODUCT_LIMIT = 24

type PaginatedProductsParams = {
  limit: number
  collection_id?: string[]
  category_id?: string[]
  id?: string[]
  order?: string
}

export default async function PaginatedProducts({
  sortBy,
  page,
  collectionId,
  categoryId,
  productsIds,
  countryCode,
}: {
  sortBy?: SortOptions
  page: number
  collectionId?: string
  categoryId?: string
  productsIds?: string[]
  countryCode: string
}) {
  // Category pages show the whole category on one page (like teknikhouse),
  // so sorting applies to every product, not just the current page. The store
  // page keeps normal pagination.
  const perPage = categoryId ? 200 : PRODUCT_LIMIT

  const queryParams: PaginatedProductsParams = {
    limit: perPage,
  }

  if (collectionId) {
    queryParams["collection_id"] = [collectionId]
  }

  if (categoryId) {
    queryParams["category_id"] = [categoryId]
  }

  if (productsIds) {
    queryParams["id"] = productsIds
  }

  // Map the sort choice to a Store API `order`. Name and date sort natively.
  // Price cannot be ordered server-side, so we still order by title here (which
  // returns a fresh, price-resolved result set) and let sortProducts reorder by
  // price afterwards.
  const ORDER_MAP: Record<string, string> = {
    title: "title",
    created_at: "-created_at",
    price_asc: "title",
    price_desc: "title",
  }
  if (sortBy && ORDER_MAP[sortBy]) {
    queryParams["order"] = ORDER_MAP[sortBy]
  }

  const region = await getRegion(countryCode)

  if (!region) {
    return null
  }

  let {
    response: { products, count },
  } = await getProductsListWithSort({
    page,
    queryParams,
    sortBy,
    countryCode,
  })

  const totalPages = Math.ceil(count / perPage)

  return (
    <>
      <ul
        className="grid grid-cols-2 w-full small:grid-cols-3 medium:grid-cols-4 gap-x-6 gap-y-8"
        data-testid="products-list"
      >
        {products.map((p) => {
          return (
            <li key={p.id}>
              <ProductPreview product={p} region={region} />
            </li>
          )
        })}
      </ul>
      {totalPages > 1 && (
        <Pagination
          data-testid="product-pagination"
          page={page}
          totalPages={totalPages}
        />
      )}
    </>
  )
}
